"""Train and evaluate the fall classifier.   Run:  python train.py
Needs:  pip install scikit-learn numpy
Writes: results.txt, fallmodel.py (copy this file to the ESP32)
"""
import csv, os, sys
import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.tree import DecisionTreeClassifier
from sklearn.model_selection import LeaveOneGroupOut, StratifiedKFold
from sklearn.metrics import confusion_matrix
from featlib import features, FEATURES

D = "data"
X, y, g, acts = [], [], [], []
for r in csv.DictReader(open(os.path.join(D, "labels.csv"))):
    rows = [[float(v) for v in l.split(",")] for l in open(os.path.join(D, r["file"])) if l.strip()]
    X.append(features([row[:3] for row in rows]))
    y.append(int(r["is_fall"])); g.append(r["subject"]); acts.append(r["activity"])
X, y, g = np.array(X), np.array(y), np.array(g)
subs = sorted(set(g))
out = []
def say(s=""):
    print(s); out.append(s)

say("Windows: %d  (falls %d, not falls %d)   Subjects: %s" % (len(y), y.sum(), (1 - y).sum(), ", ".join(subs)))
QUICK = "--quick" in sys.argv
if len(subs) < 3 and not QUICK:
    sys.exit("Need at least 3 subjects for subject-wise testing.\n"
             "To just try a model on the board with one person, run:  python train.py --quick")
if len(subs) < 3:
    say("*** QUICK MODE: one or two people only. These scores are NOT valid for the paper. ***")

def rates(yt, yp):
    tn, fp, fn, tp = confusion_matrix(yt, yp, labels=[0, 1]).ravel()
    sens = tp / (tp + fn) if tp + fn else float("nan")
    spec = tn / (tn + fp) if tn + fp else float("nan")
    return tp, fn, tn, fp, sens, spec, (tp + tn) / len(yt)

def make():
    return RandomForestClassifier(n_estimators=15, max_depth=5, min_samples_leaf=2,
                                  class_weight="balanced", random_state=1)

# leave-one-subject-out: the test subject is never in training
pred = np.zeros(len(y), int); base = ((X[:, 0] >= 3.0) & (X[:, 0] <= 14.0)).astype(int)
splits = LeaveOneGroupOut().split(X, y, g) if len(subs) >= 3 else StratifiedKFold(5, shuffle=True, random_state=1).split(X, y)
for tr, te in splits:
    m = make().fit(X[tr], y[tr]); pred[te] = m.predict(X[te])
say("\n%s results (all windows pooled):" % ("Leave-one-subject-out" if len(subs) >= 3 else "5-fold (NOT subject-independent)"))
for name, p in (("Random Forest", pred), ("Old rule 3-14 g", base)):
    tp, fn, tn, fp, se, sp, ac = rates(y, p)
    say("  %-16s TP=%d FN=%d TN=%d FP=%d  sensitivity=%.1f%%  specificity=%.1f%%  accuracy=%.1f%%"
        % (name, tp, fn, tn, fp, 100 * se, 100 * sp, 100 * ac))
say("\nPer subject (Random Forest):")
for s in subs:
    k = g == s; tp, fn, tn, fp, se, sp, ac = rates(y[k], pred[k])
    say("  %-4s n=%d  sens=%.0f%%  spec=%.0f%%" % (s, k.sum(), 100 * se, 100 * sp))
say("\nPer activity: share of windows called FALL")
for a in sorted(set(acts)):
    k = np.array([x == a for x in acts]); say("  %-20s n=%2d  called fall: %3.0f%%" % (a, k.sum(), 100 * pred[k].mean()))
m = make().fit(X, y)
say("\nFeature importance:")
for n, v in sorted(zip(FEATURES, m.feature_importances_), key=lambda t: -t[1]):
    say("  %-14s %.2f" % (n, v))
open("results.txt", "w").write("\n".join(out))

# ---- export to MicroPython: a vote of small if/else trees ----
lines = ["# generated by train.py - do not edit", "def _t%d(f):"]
code = ["# generated by train.py - do not edit"]
for i, est in enumerate(m.estimators_):
    t = est.tree_
    code.append("def _t%d(f):" % i)
    def walk(n, ind):
        if t.feature[n] < 0:
            code.append("%sreturn %.3f" % (" " * ind, t.value[n][0][1] / t.value[n][0].sum()))
            return
        code.append("%sif f[%d] <= %.4f:" % (" " * ind, t.feature[n], t.threshold[n]))
        walk(t.children_left[n], ind + 4)
        code.append("%selse:" % (" " * ind))
        walk(t.children_right[n], ind + 4)
    walk(0, 4)
code.append("def fall_probability(f):")
code.append("    return (%s) / %d" % (" + ".join("_t%d(f)" % i for i in range(len(m.estimators_))), len(m.estimators_)))
open("fallmodel.py", "w").write("\n".join(code) + "\n")
say("\nSaved results.txt and fallmodel.py (%d lines)" % len(code))
